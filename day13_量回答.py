"""Day 13：生成层的尺子 —— 判「话里的那个事实在不在」，不判字一不一样。

结构分四块，从上到下：
  一、题库（数据）
  二、判分函数（逻辑，只写这一遍）
  三、正式跑分
  四、反向测试（证明尺子抓得住错的）
"""
from day06_files import ChatBot


# ============ 一、题库（数据） ============
回答题库 = [
    {
        "问": "升档要连续几天不断档？",
        "必须出现": ["5", "天"],
        "绝不能出现": [],
        "说明": "数字类：答案必须带 5",
    },
    {
        "问": "这台电脑C盘还有多少容量?",
        "必须出现": ["241"],          # ← 方括号必须要有，否则会变成 ['2','4','1']
        "绝不能出现": [],
        "说明": "数字类",
    },
    {
        "问": "主力电脑是什么",
        "必须出现": ["联想", "拯救者"],
        "绝不能出现": [],
        "说明": "事实类",
    },
    {
        "问": "杭州今天天气怎么样？",
        "必须出现": ["没有"],
        "绝不能出现": ["晴", "雨", "度", "℃"],
        "最多字数": 20,
        "说明": "拒答题：必须简短地承认没有",
    },
]


# ============ 二、判分（只写这一遍） ============
def 判(c, got):
    """判一份答案。返回 (是否通过, 漏了, 多了, 太啰嗦)"""
    缺了 = [k for k in c["必须出现"] if k not in got]
    多了 = [k for k in c["绝不能出现"] if k in got]
    太啰嗦 = ("最多字数" in c) and (len(got) > c["最多字数"])
    ok = (not 缺了) and (not 多了) and (not 太啰嗦)
    return ok, 缺了, 多了, 太啰嗦


# ============ 三、正式跑分 ============
bot = ChatBot()
通过 = 0

print("=" * 60)
print("正式跑分")
print("=" * 60)

for i, c in enumerate(回答题库, 1):
    got = bot.ask_with_files(c["问"], f"生成{i}")
    ok, 缺了, 多了, 太啰嗦 = 判(c, got)

    if ok:
        通过 += 1
    print(f"第{i}题 {'✓' if ok else '✗'}  {c['问']}")
    print(f"    回答：{got}")
    if 缺了:
        print(f"    漏了：{缺了}")
    if 多了:
        print(f"    不该出现：{多了}")
    if 太啰嗦:
        print(f"    太啰嗦：{len(got)} 字，超过 {c['最多字数']}")
    print()

print(f"生成层 {通过}/{len(回答题库)}")


# ============ 四、反向测试 ============
print()
print("=" * 60)
print("反向测试：尺子能不能对错的东西说「错」")
print("=" * 60)

假答案 = "根据资料，升档需要连续 7 天不断档。"
ok, 缺了, 多了, 太啰嗦 = 判(回答题库[0], 假答案)
print("① 假答案（说了 7 天）→", "通过（尺子坏了！）" if ok else f"✗ 漏了{缺了}")

q = "杭州今天天气怎么样？"
ctx = bot.retrieve(q, bot.chunks, k=2)
坏prompt = f"请参考下面这些资料回答问题。\n资料：{ctx}\n问题：{q}"
坏答案 = bot.ask(坏prompt, "坏")

ok, 缺了, 多了, 太啰嗦 = 判(回答题库[3], 坏答案)
if ok:
    print("② 坏答案 → 通过（尺子坏了！）")
else:
    原因 = []
    if 缺了:
        原因.append(f"漏了{缺了}")
    if 多了:
        原因.append(f"多了{多了}")
    if 太啰嗦:
        原因.append(f"太啰嗦（{len(坏答案)} 字）")
    print("② 坏答案 → ✗ " + "、".join(原因))
