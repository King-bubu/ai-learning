def 判(题, got):
    """判一道题。返回 (是否通过, 说明)"""
    低 = got
    if 题["类"] == "陷阱":
        编了 = [k for k in 题["禁含"] if k.lower() in 低.lower()]
        if 编了:
            return False, f"编了具体值：{编了}"
        return True, "没编，稳住了"

    缺 = []
    for k in 题["必含"]:
        写法 = [w for w in k.split("|") if w in 低]
        if not 写法:
            缺.append(k)
    if 缺:
        return False, f"没答到：{缺}"
    if 题["上限"] and len(低) > 题["上限"]:
        return False, f"太啰嗦（{len(低)} 字 > {题['上限']}）"
    return True, "答到了"


def 跑一遍():
    bot = ChatBot()
    print(f"库里共 {len(bot.chunks)} 段\n")
    过 = 0
    明细 = []
    for 题 in 题目:
        答 = bot.ask_with_files(题["问"], f"第一关第{题['id']}题")
        ok, 说明 = 判(题, 答)
        过 += ok
        明细.append((题, 答, ok, 说明))
        记 = "✓" if ok else "✗"
        print(f"[{记}] 第{题['id']:>2}题 {题['类']}｜{题['问']}")
        print(f"      答：{答[:90]}")
        print(f"      判：{说明}")
        print()
    print("=" * 56)
    print(f"总分：{过}/10")
    return 过, 明细


