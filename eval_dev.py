# 第一版为什么废：9 题全对，MRR 1.0000。
# **满分 = 这把尺子也废了** —— 跟昨天 test 集 10/10 之后失去判断力一模一样。
# 一个只会说"你很好"的测试集，等于没有测试集。
#
# 这一版加了两条设计原则：
#
#   ① 必须留几条"现在就错"的题。
#      错题不是 bug，是靶子。没有靶子，你没法知道自己是变好还是变坏。
#      这一版留了两个硬靶子（[3] 投简历、[10] 深度学习框架），
#      它们现在拿 0 分，因为整段关键词都被替换掉了。
#
#   ② 错的题要和"对的题"同段配对。
#      这是最有用的设计：同一段资料，两种问法，一对一挂。
#      那就能断定不是"这段找不到"，而是"某个词害的"。
#      本集有三对：[3]、[5]、以及 [0]（对照组在 test 集里）。
#
#   ③ 难度要有梯度。全放同义词题，分数永远 0，
#      你既看不出进步，也看不出退步。
#
#   ④ 覆盖 test 没考过的段（日志规则 / 时间线 / git push / PyTorch 版本）。
#      test 的 10 题只考了 12 段里的 7 段，「硬件参数」一段占 4 题。
#
# ==================================================================
# type 字段（以后可以按它分组统计）
# ==================================================================
#   直问      —— 基本用原文的词，难度最低。应该永远对，用来防退化。
#   换句式    —— 关键词保留，语序和说法换了。最该测的一类。
#   同义词    —— 刻意把关键词换成同义词。**现在会错，这是故意的**，
#                它标的是系统的能力边界，不是你改坏了。
#   跨段      —— 答案分散在两段，检索只能返回 k 段，天生难。
#   资料里没有 —— expect 写 None，检索层不评分，等以后接生成层用。
#
# ==================================================================
# 当前基线（2026-10-29，k=2，raw 打分）：hit@2 = 6/9 ≈ 0.67，MRR ≈ 0.61
# 每条的"现在排第几"写在注释里。改完代码，先看这几行的排名有没有变。
# ==================================================================

